import fs from "node:fs";
import path from "node:path";
import { parseSymbolSvg, verifySymbols, type SymbolCatalog } from "./material-symbols";
const ROOT = path.resolve(import.meta.dir, "..");
const HEADER = "// Generated by scripts/icon-entries.ts. Do not edit.\n";
const portable = (file: string) => file.split(path.sep).join("/");

/** Every icon shares one renderer while artwork installations remain explicit imports. */
export async function writeIconEntries(root = ROOT): Promise<SymbolCatalog> {
  const catalog = await verifySymbols(root),
    directory = path.join(root, "src/generated/icons"),
    outputs = new Map<string, string>(),
    familyEntries = new Map<string, string[]>();
  const put = (file: string, content: string) => outputs.set(path.join(directory, file), HEADER + content);
  for (const symbol of catalog.symbols) {
    const name = symbol.name.replaceAll("_", "-"),
      base = symbol.assets.find((asset) => asset.family === "rounded" && !asset.filled)!;
    const geometry = parseSymbolSvg(await Bun.file(path.join(root, "assets/material-symbols", base.file)).text());
    put(`records/${name}.ts`, `import { IconArtwork } from "../../../shared/icon-artwork";\nexport const artwork = new IconArtwork(${JSON.stringify(symbol.name)}, ${JSON.stringify(geometry)});\n`);
    put(
      `classes/${name}-icon.ts`,
      `import { AcmeIconElement } from "../../../shared/icon-element";\nimport { artwork } from "../records/${name}";\n\nexport class ${symbol.className} extends AcmeIconElement {\n  protected get artwork() { return artwork; }\n}\ndeclare global { interface HTMLElementTagNameMap { ${JSON.stringify(symbol.tag)}: ${symbol.className}; } }\n`,
    );
    for (const asset of symbol.assets) {
      const style = `${asset.family}/${asset.filled ? "filled" : "unfilled"}`,
        file = `artwork/${style}/${name}.ts`;
      const geometry = asset === base ? undefined : parseSymbolSvg(await Bun.file(path.join(root, "assets/material-symbols", asset.file)).text());
      put(
        file,
        `import { artwork } from "../../../records/${name}";\n${geometry ? `artwork.add(${JSON.stringify(asset.family)}, ${asset.filled}, ${JSON.stringify(geometry)});\n` : ""}export { artwork };\n`,
      );
      const members = familyEntries.get(style) ?? [];
      members.push(name);
      familyEntries.set(style, members);
    }
  }
  for (const [style, names] of familyEntries) put(`families/${style}.ts`, names.map((name) => `import "../../artwork/${style}/${name}";\n`).join(""));
  put("index.ts", catalog.symbols.map((symbol) => `export { ${symbol.className} } from "./classes/${symbol.name.replaceAll("_", "-")}-icon";\n`).join(""));
  put("all.ts", catalog.symbols.map((symbol) => `import "../../define/${symbol.name.replaceAll("_", "-")}-icon";\n`).join(""));
  for (const [file, content] of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    if (fs.existsSync(file)) {
      const previous = fs.readFileSync(file, "utf8");
      if (!previous.startsWith(HEADER)) throw new Error(`Refusing to overwrite authored icon entry: ${file}`);
      if (previous === content) continue;
    }
    fs.writeFileSync(file, content);
  }
  if (fs.existsSync(directory))
    for (const relative of new Bun.Glob("**/*.ts").scanSync({ cwd: directory })) {
      const file = path.join(directory, relative);
      if (!outputs.has(file) && fs.readFileSync(file, "utf8").startsWith(HEADER)) fs.unlinkSync(file);
    }
  await Bun.write(path.join(directory, "entries.json"), JSON.stringify({ revision: catalog.revision, files: [...outputs.keys()].map((file) => portable(path.relative(root, file))) }, null, 2) + "\n");
  return catalog;
}
if (import.meta.main) {
  const catalog = await writeIconEntries();
  console.log(`icons: ${catalog.symbols.length} classes with explicit artwork imports`);
}
