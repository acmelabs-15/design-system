import type { DiagnosticMetadata, ComponentContract } from "../packages/devtools/src/diagnostics";
import type { Package } from "custom-elements-manifest/schema";
import path from "node:path";

export function diagnosticMetadata(manifest: Package, tokenProperties: readonly string[]): DiagnosticMetadata {
  const version = (manifest as Package & { "x-acme-version"?: string })["x-acme-version"];
  if (!version) {
    throw new Error("Inspector metadata requires a release-versioned manifest");
  }
  const contracts: ComponentContract[] = [],
    tags: Record<string, number> = {},
    byContract = new Map<string, number>();
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (declaration.kind !== "class" || !("tagName" in declaration) || !declaration.tagName) {
        continue;
      }
      const component = declaration as typeof declaration & {
        attributes?: { name: string }[];
        events?: { name: string }[];
        cssProperties?: { name: string }[];
        "x-acme-states"?: { name: string }[];
      };
      const contract: ComponentContract = {
        properties: (component.members ?? [])
          .filter((member) => member.kind === "field" && !member.static && member.privacy !== "private" && member.privacy !== "protected")
          .map((member) => member.name)
          .sort(),
        attributes: (component.attributes ?? []).map((attribute) => attribute.name).sort(),
        events: (component.events ?? []).map((event) => event.name).sort(),
        states: (component["x-acme-states"] ?? []).map((state) => state.name).sort(),
        cssProperties: (component.cssProperties ?? []).map((property) => property.name).sort(),
      };
      const key = JSON.stringify(contract);
      let index = byContract.get(key);
      if (index === undefined) {
        index = contracts.length;
        contracts.push(contract);
        byContract.set(key, index);
      }
      tags[component.tagName as string] = index;
    }
  }
  return { version, contracts, tags, tokens: [...new Set(tokenProperties)].sort() };
}
export async function writeDevtoolsMetadata(root = path.resolve(import.meta.dir, "..")) {
  const manifest = await Bun.file(path.join(root, "dist/custom-elements.json")).json();
  const tokens = await Bun.file(path.join(root, "dist/tokens.json")).json();
  const result = diagnosticMetadata(
    manifest,
    tokens.tokens.map((token: { cssProperty: string }) => token.cssProperty),
  );
  const pkg = await Bun.file(path.join(root, "packages/devtools/package.json")).json();
  if (pkg.version !== result.version) {
    throw new Error("Inspector package and core versions differ");
  }
  await Bun.write(
    path.join(root, "packages/devtools/src/generated/metadata.ts"),
    `// Generated by scripts/devtools-metadata.ts from the public manifest and token catalog.\nimport type { DiagnosticMetadata } from "../diagnostics";\nexport const metadata: DiagnosticMetadata = ${JSON.stringify(result)};\n`,
  );
  return result;
}
if (import.meta.main) {
  const result = await writeDevtoolsMetadata();
  console.log(`Inspector metadata: ${Object.keys(result.tags).length} elements, ${result.contracts.length} shared contracts`);
}
