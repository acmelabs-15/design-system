// Writes the element reference the design-system skill reads: one section per docs page with the
// lede, every example's markup and the API of each element, all from the same sources as the
// docs site. Run: bun docs-src/skill-reference.ts [out.md]   (default: the skill's references/).
import fs from "node:fs";
import path from "node:path";
import { readApi } from "./api";
import { formatHtml } from "./format";
import { loadDocs } from "./pages/components/index";
import type { Doc } from "./site";

const ROOT = path.resolve(import.meta.dir, "..");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")) as { version: string };
const out = process.argv[2] ?? path.join(process.env.HOME ?? "", ".claude/skills/design-system/references/elements.md");
const api = readApi();
const byTag = new Map(api.map((e) => [e.tag, e]));
const docs: Doc[] = (await loadDocs()).sort((a, b) => a.title.localeCompare(b.title));

const strip = (s: string) =>
  s
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();
const lines: string[] = [
  `# Elements of @acmelabs/design-system ${pkg.version}`,
  "",
  "Generated by `docs-src/skill-reference.ts` in the design-system repository; edit the docs sources, not this file.",
  "One section per docs page: what it is, the markup of every example (copy these shapes), then the API of each element.",
  "Attributes reflect to properties; array and object values take JSON in the attribute. Events bubble and are composed.",
  `Live docs: https://acmelabs-15.github.io/design-system/ (a page per section: /components/<id>).`,
  "",
  "## Index",
  "",
  ...docs.map((d) => `- [${d.title}](#${d.id})${d.house ? " (house)" : ""}: ${(d.tags ?? []).map((t) => `\`<${t}>\``).join(", ")}`),
  "",
];
for (const d of docs) {
  lines.push(`## ${d.title}`, "", `<a id="${d.id}"></a>`, "", `${strip(d.lede)}${d.house ? " House component; Geist has no page for it." : ""}`, "");
  for (const e of d.examples) {
    lines.push(`### ${e.h}`, "");
    if (e.p) lines.push(strip(e.p), "");
    lines.push("```html", formatHtml((e.code ?? e.html) + (e.script ? `\n<script>\n${e.script.trim()}\n</script>` : "")), "```", "");
  }
  for (const t of d.tags ?? []) {
    const el = byTag.get(t);
    if (!el) continue;
    lines.push(`### \`<${t}>\``, "");
    if (el.doc) lines.push(el.doc, "");
    if (el.props.length) {
      lines.push("| Attribute | Property | Type | Default | Description |", "|---|---|---|---|---|");
      for (const p of el.props)
        lines.push(
          `| ${p.attribute === false ? "—" : `\`${p.attribute}\``} | \`${p.name}\` | \`${p.type.replace(/\|/g, "\\|")}\` | ${p.default ? `\`${p.default.replace(/\|/g, "\\|")}\`` : "—"} | ${p.doc.replace(/\|/g, "\\|")} |`,
        );
      lines.push("");
    }
    if (el.slots.length) lines.push(`Slots: ${el.slots.map((s) => `\`${s}\``).join(", ")}`, "");
    if (el.events.length) lines.push(`Events: ${el.events.map((s) => `\`${s}\``).join(", ")}`, "");
  }
  if (d.practices) {
    for (const [k, v] of Object.entries(d.practices)) lines.push(`**${k}.** ${v.join(" ")}`, "");
  }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`wrote ${out}: ${docs.length} sections, ${api.length} elements`);
