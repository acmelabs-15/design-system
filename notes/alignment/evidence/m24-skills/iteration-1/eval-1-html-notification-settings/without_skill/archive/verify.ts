import { chromium } from '/Users/peterkloss/Library/Caches/acme-design-system/browser-checks/node_modules/playwright/index.mjs';
const root = '/tmp/acme-m24-evals/html-baseline';
const pkg = '/tmp/acme-m24-evals/node_modules/@acmelabs/design-system';
const prefix = '/npm/@acmelabs/design-system@0.2.0/';
const server = Bun.serve({ port: 0, fetch(request) {
  const path = new URL(request.url).pathname;
  const file = Bun.file(path.startsWith(prefix) ? pkg + '/' + path.slice(prefix.length) : root + '/index.html');
  return new Response(file, {headers: {'Access-Control-Allow-Origin': '*'}});
}});
const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true});
const page = await browser.newPage({viewport:{width:900,height:850}});
const errors:string[] = [];
const requests:string[] = [];
page.on('pageerror',error=>errors.push(String(error)));
page.on('request',request=>requests.push(request.url()));
await page.route('https://cdn.jsdelivr.net/npm/@acmelabs/design-system@0.2.0/**', async route=>{
 const response=await fetch(`http://localhost:${server.port}${new URL(route.request().url()).pathname}`);
 await route.fulfill({status:response.status,headers:Object.fromEntries(response.headers),body:Buffer.from(await response.arrayBuffer())});
});
const result:any={variant:'html-baseline',artifact:root+'/index.html',packageVersion:'0.2.0',consumerSkillRead:false,checks:{},errors};
try {
 await page.goto(`http://localhost:${server.port}`);
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('*')).filter(e=>e.localName.startsWith('acme-')).every(e=>customElements.get(e.localName)));
 result.checks.registration=await page.evaluate(()=>Array.from(new Set(Array.from(document.querySelectorAll('*')).map(e=>e.localName).filter(n=>n.startsWith('acme-')))).map(tag=>({tag,registered:!!customElements.get(tag)})));
 result.initial=await page.evaluate(()=>Object.fromEntries(new FormData(document.querySelector('form')!)));
 result.accessibility=await page.locator('main > form').ariaSnapshot();
 await page.locator('acme-input input').fill('changed@example.com');
 await page.locator('acme-select').getByRole('combobox').click();
 await page.locator('acme-option[value=pro]').click();
 await page.getByRole('switch',{name:'Email notifications'}).click();
 await page.getByRole('button',{name:'Save',exact:true}).click();
 result.changedReceipt=JSON.parse(await page.locator('#receipt').innerText());
 result.checks.changedValues=JSON.stringify(result.changedReceipt)===JSON.stringify([['email','changed@example.com'],['plan','pro']]);
 await page.locator('acme-input input').fill('');
 result.required=await page.evaluate(()=>({valid:document.querySelector('form')!.checkValidity(),missing:(document.querySelector('acme-input') as any).validity.valueMissing}));
 const prior=await page.locator('#receipt').innerText();
 await page.getByRole('button',{name:'Save',exact:true}).click();
 result.checks.requiredBlocksSave=!result.required.valid && result.required.missing && await page.locator('#receipt').innerText()===prior;
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 result.reset=await page.evaluate(()=>Object.fromEntries(new FormData(document.querySelector('form')!)));
 result.checks.resetInitialValues=JSON.stringify(result.reset)===JSON.stringify(result.initial);
 await page.getByRole('button',{name:'Save',exact:true}).click();
 result.resetReceipt=JSON.parse(await page.locator('#receipt').innerText());
 await page.screenshot({path:root+'/verified.png',fullPage:true});
 result.checks.selectiveOnly=!requests.some(u=>/\/all\.js|standalone|devtools/.test(u));
 result.checks.noNetworkSubmission=requests.every(u=>u.startsWith(`http://localhost:${server.port}`)||u.startsWith('https://cdn.jsdelivr.net/npm/@acmelabs/design-system@0.2.0/'));
} catch(error) {result.failure=String(error);await page.screenshot({path:root+'/failure.png',fullPage:true});}
const cdp = await page.context().newCDPSession(page);
const ax = await cdp.send('Accessibility.getFullAXTree');
result.nativeAccessibility = ax.nodes.filter(n=>['textbox','combobox','switch','button'].includes(n.role?.value)).map(n=>({role:n.role.value,name:n.name?.value}));
result.checks.emailAccessibleName = result.nativeAccessibility.some(n=>n.role==='textbox' && n.name==='Email');
result.checks.planAccessibleName = result.nativeAccessibility.some(n=>n.role==='combobox' && n.name==='Plan');
await cdp.detach();
result.notes = ['First artifact omitted explicit option definition; fixed after registration check failed. See attempt-1.json.', 'Initial harness form selector crossed shadow roots; narrowed to main > form. See attempt-2.json.', 'Role-based Pro option lookup failed; CSS option lookup succeeded. See attempt-3.json.', 'Playwright role/name lookup does not resolve acme-field labels. Native Chromium accessibility tree is the authoritative accessible-name check.', 'CDN publication was not tested. Versioned requests were routed through local Bun server to the installed package.'];
result.requests=requests;
result.pass=!result.failure && errors.length===0 && Object.values(result.checks).every(v=>v!==false);
await Bun.write(root+'/result.json',JSON.stringify(result,null,2));
await browser.close();server.stop();
console.log(JSON.stringify(result,null,2));
